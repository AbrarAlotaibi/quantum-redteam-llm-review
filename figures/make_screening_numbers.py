"""Numbers of the eligibility screening of the sampling frame, as LaTeX macros.

Usage:  python figures/make_screening_numbers.py      (from the repository root)
        python figures/make_screening_numbers.py <frame_screening folder> <selected_studies.csv> <out .tex>
Every number that the article quotes on the screening of the sampling frame (Section 2.3, the
flow figure, and the table of eligible records by role) is computed here from the screening
records and written to figures/data/screening_numbers.tex; none is typed into the manuscript.

The macros eligible, oneonly and neither count the records by the two main screeners after the
abstracts were retrieved; the pool macros (poolR1 ...) count the records eligible by both.
The macros that start with adj and final give the outcome after the third screener.
"""
import csv, sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
args = sys.argv[1:] or [ROOT / "search" / "frame_screening", ROOT / "search" / "selected_studies.csv",
                        ROOT / "figures" / "data" / "screening_numbers.tex"]
d, sel_path, out = Path(args[0]), args[1], Path(args[2])
rows = lambda p: list(csv.DictReader(open(p, encoding="utf-8", newline="")))
fs, roles, sel = rows(d / "phase4_eligibility" / "frame_screening.csv"), rows(d / "phase5_selection" / "eligible_by_role.csv"), rows(sel_path)


def kappa(pairs):
    n = len(pairs)
    po = sum(a == b for a, b in pairs) / n
    ca, cb = Counter(a for a, _ in pairs), Counter(b for _, b in pairs)
    pe = sum(ca[c] * cb[c] for c in set(ca) | set(cb)) / n / n
    return po, (po - pe) / (1 - pe)


el = lambda c: c in ("IC1", "IC2")
pairs = [(r["code_A"], r["code_B"]) for r in fs]
po, k_all = kappa(pairs)
_, k_el = kappa([(el(a), el(b)) for a, b in pairs])
both = [r for r in roles if r["eligible_by"] == "both screeners"]
_, k_role = kappa([(r["role_A"], r["role_B"]) for r in both])
st = Counter((r["decided_by"], r["final"]) for r in fs)
rep = [r for r in sel if r["route"] == "representative"]
both_uids = {r["uid"] for r in fs if r["decided_by"] == "both screeners" and r["final"] == "eligible"}
in_frame = [r for r in rep if r["uid"]]
assert all(r["uid"] in both_uids for r in in_frame), "a selected study in the frame is not eligible by both screeners"
fmt = lambda n: "{:,}".format(n).replace(",", "{,}")
adj_el, adj_not = st[("third screener", "eligible")], st[("third screener", "not eligible")]
vals = {
    "screened": fmt(len(fs)), "eligible": fmt(st[("both screeners", "eligible")]), "oneonly": fmt(adj_el + adj_not),
    "neither": fmt(st[("both screeners", "not eligible")]),
    "agreepct": "%d" % round(100 * po), "kappaall": "%.2f" % k_all, "kappaelig": "%.2f" % k_el, "kapparole": "%.2f" % k_role,
    "rep": str(len(rep)), "inframe": str(len(in_frame)), "snowball": str(len(rep) - len(in_frame)),
    "icone": str(sum(r["criterion"] == "IC1" for r in rep)), "ictwo": str(sum(r["criterion"] == "IC2" for r in rep)),
    "roleunassigned": str(sum(not r["role"] for r in both)),
    "adjeligible": fmt(adj_el), "adjnot": fmt(adj_not), "finaleligible": fmt(st[("both screeners", "eligible")] + adj_el),
    "finalnot": fmt(st[("both screeners", "not eligible")] + adj_not),
    "rescreened": fmt(sum(r["screening_round"] != "1" for r in fs)), "noabstract": fmt(sum(r["abstract_available"] == "no" for r in fs)),
}
for role in ("R1", "R2", "R3", "R4", "R5", "R6"):
    vals["pool" + role] = fmt(sum(r["role"] == role for r in both))
    vals["finalpool" + role] = fmt(sum(r["role"] == role for r in roles))
lines = ["%% Generated by make_screening_numbers.py from the frame screening records. Do not edit.",
         "\\newcommand{\\scr}[1]{\\csname scr@#1\\endcsname}"]
lines += ["\\expandafter\\def\\csname scr@%s\\endcsname{%s}" % kv for kv in vals.items()]
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
for kv in vals.items():
    print("%-15s %s" % kv)
